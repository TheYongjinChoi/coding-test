set.seed(1)
n <- nrow(x_train)   # 관측치 수 객체에 저장
p <- ncol(x_train)   # 예측변수 수 객체에 저장

n_hidden <- 5        # 은닉층 유닛 수를 5로 지정
lr       <- 0.01     # 학습률 지정. 여기에서는 0.01로 고정합니다.
n_iter   <- 2000     # 경사하강 반복 횟수(epoch)

# ── 초기화 ────────────────────────────────────────────────
# 초기화는 경사하강이 어디서 출발할지 정하는 단계입니다.
# 학습으로 바뀔 값이므로 출발점으로서 적절하기만 하면 됩니다.
# 가중치 W1, w2는 무작위 값으로, 편향 b1, b2는 고정값으로 시작합니다.

# W1: 입력 -> 은닉층 가중치
# 회귀계수가 실수인 것처럼 가중치도 실수여야 하므로 rnorm() 함수를 사용해 0을 중심으로 대칭인 정규분포에서 뽑습니다. 유닛마다 다른 값에서 출발해야 5개가 서로 다른 방향을 탐색하므로 무작위로 추출합니다. 유닛 하나가 회귀식 하나이고 은닉층 유닛이 5개로 n_hidden에 저장해 두었으므로 행의 수가 예측변수의 수인 p, 열이 5개인 행렬을 생성합니다.
W1 <- matrix(_____(p * _____, sd = 0.1), nrow = p)

# 은닉층 편향
# rep(a, b)는 값 a를 b번 반복한 벡터를 만듭니다. 편향은 0에서 출발하고, 은닉층 유닛 수 길이의 벡터로 만들어 둡니다.
b1 <- rep(0, _____)

# w2: 은닉층 -> 출력 가중치
# 은닉층 유닛 5개를 받아 하나의 예측값으로 합치기 때문에 5개의 가중치 값이 필요합니다. 은닉층 가중치와 마찬가지로 0을 중심으로 무작위 추출합니다.
w2 <- rnorm(_____, sd = 0.1)

# 출력 편향: 빠르게 수렴할 수 있도록 y의 평균에서 시작
b2 <- mean(y_train)

loss_history <- rep(NA, n_iter)   # 반복마다 성능비교를 위해 계산된 손실을 기록할 빈 리스트 생성

# ── 학습 시작 ────────────────────────────────────────────────
# 아래 세 단계를 n_iter에 저장한 횟수만큼 반복하면서 가중치를 조금씩 다듬어 갑니다.

for (iter in 1:_____) {   # 1부터 위에서 정의한 n_iter까지 반복합니다

  # ── 1. 순전파: 현재 가중치로 예측값 계산 ────────────────
  # 은닉층 입력: 은닉층 유닛 5개의 값을 모든 관측치에 대해 한 번에 계산합니다.
  # 유닛 하나는 Z = b + (각 예측변수 × 그 변수의 가중치)의 합 형태로 회귀식과 모양이 같습니다.
  # 관측치 i, 유닛 1이라면 Z_i1 = b_1 + w_11*x_i1 + w_21*x_i2 + ... + w_p1*x_ip 이고,
  # 유닛이 5개이므로 결과는 열이 5개인 행렬이 됩니다.
  #   x_train %*% W1: %*%은 행렬곱을 의미하며, w_11*x_i1 + ... + w_p1*x_ip 부분을 계산
  #   rep(b1, each = n): 편향 b_1을 각 열에 더하기 위한 장치
  Z    <- x_train %*% _____ + rep(b1, each = n)

  # 은닉층 출력: 활성화 함수를 항등함수로 지정했으므로 Z를 그대로 통과시킵니다.
  H    <- _____

  # 은닉층 유닛 5개를 하나의 예측값으로 합칩니다. Z를 계산할 때와 같은 방식입니다.
  pred <- as.vector(H %*% w2 + b2)   # 최종 예측값(관측치 n개 만큼의 벡터)

  # 이번 반복의 훈련 손실을 기록합니다. 학습에는 쓰이지 않고 나중에 그래프용입니다.
  loss_history[iter] <- mean((y_train - _____)^2)

  # ── 2. 역전파: 손실을 각 가중치로 미분 ──────────────────
  # 각 가중치를 조금 늘렸을 때 손실이 얼마나 변하는지(= 기울기)를 구하는 단계입니다.
  # 여기서는 기울기만 구하고, 가중치를 실제로 바꾸는 것은 3단계입니다.
  # 미분은 손으로 미리 끝내두었고, 아래 코드는 그 결과 공식을 계산할 뿐입니다.
  # 출력 쪽에서 시작해 은닉층, 입력 쪽으로 거슬러 내려갑니다.

  # 손실 L = mean((pred - y)^2)을 pred로 미분하면 2 * (pred - y) / n 입니다.
  # 2는 제곱을 미분하며 나온 계수, /n은 평균의 1/n입니다.
  # 핵심은 (pred - y_train), 즉 잔차입니다. 어느 방향으로 얼마나 틀렸는지 알려줍니다.
  dpred   <- 2 * (pred - _____) / n

  # w2의 기울기: w2에 곱해지던 값이 H이므로 dpred에 H를 곱합니다.
  # t(H)로 전치해야 차원이 맞아 w2와 같은 길이 5가 나옵니다.
  # b2의 기울기: b2는 모든 관측치의 예측에 1씩 기여하므로 dpred를 그대로 더합니다.
  grad_w2 <- as.vector(t(H) %*% _____)
  grad_b2 <- sum(dpred)

  # 여기서부터 은닉층입니다. 은닉층에는 정답이 없으므로,
  # 출력 쪽에서 계산한 신호를 되돌려 받아야 합니다.
  # pred = b2 + H1*w2[1] + ... + H5*w2[5] 이므로 H로 미분하면 w2만 남습니다.
  # w2는 유닛 j가 예측에 미치는 영향의 크기이고,
  # dpred는 그 예측이 어느 쪽으로 얼마나 틀렸는지입니다.
  # 둘을 곱해야 "유닛 j를 어느 쪽으로 움직여야 손실이 주는가"가 나옵니다.
  dH <- matrix(dpred, ncol = 1) %*% matrix(w2, nrow = 1)

  # 활성화 함수를 거슬러 올라갑니다. 항등함수의 도함수는 1이므로 그대로 통과합니다.
  dZ <- _____

  grad_W1 <- t(_____) %*% dZ   # W1의 기울기: W1에 곱해지던 값이 x_train이므로 곱합니다.
  grad_b1 <- colSums(dZ)         # b1의 기울기: b2 때와 같은 논리로 유닛별(열별)로 더합니다.

  # ── 3. 갱신: 기울기 반대 방향으로 조금 이동 ─────────────
  # 기울기는 손실이 커지는 방향이므로 빼 줍니다.
  # lr(학습률)을 기울기에 곱해 한 번에 움직일 폭을 정합니다.
  # 위 기울기는 모두 갱신 전 가중치 기준이므로, 계산이 끝난 뒤 네 뭉치를 한꺼번에 적용합니다.
  W1 <- W1 - lr * _____
  b1 <- b1 - lr * grad_b1
  w2 <- w2 - lr * grad_w2
  b2 <- b2 - lr * _____
}

# ── 테스트 손실 ───────────────────────────────────────────
# 학습이 끝난 가중치로 테스트 데이터를 예측합니다. 순전파와 같은 계산입니다.
n_test <- nrow(x_test)
Z_test <- x_test %*% W1 + rep(b1, each = n_test)
p_test <- as.vector(Z_test %*% w2 + b2)
mse_id <- mean((y_test - p_test)^2)

# ── lm()과 비교 ───────────────────────────────────────────
# 훈련·테스트 모두 data.frame()으로 만들어야 열 이름이 일치해 predict()가 작동합니다.
train_df <- data.frame(y = y_train, x_train)
test_df  <- data.frame(x_test)

lm_fit <- lm(y ~ ., data = train_df)          # y ~ . : 나머지 열 전부를 예측변수로
p_lm   <- predict(lm_fit, newdata = test_df)
mse_lm <- mean((y_test - p_lm)^2)

plot(loss_history, type = "l",
    xlab = "Epoch", ylab = "Training MSE",
    main = "Linear activation")

# 두 값이 사실상 같다면, 은닉층이 있어도 결국 선형모형이라는 뜻입니다.
